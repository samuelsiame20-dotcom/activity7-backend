// server.js: Campus Maintenance Requests API (ICT251 Activity 7).
require("dotenv").config();
const express = require("express");
const cors = require("cors");
const pool = require("./db");
const { initDatabase } = require("./scripts/init-db");
const { STATUSES, FIELD_RULES } = require("./validation");

const app = express();

// Render sits behind a proxy; trust it so req.protocol reports "https".
app.set("trust proxy", 1);

// CLIENT_ORIGINS = comma-separated list of frontend URLs allowed to call this API
// from a browser (e.g. your Netlify site). Postman and curl are not affected by CORS.
const origins = (process.env.CLIENT_ORIGINS || "")
  .split(",")
  .map((value) => value.trim())
  .filter(Boolean);
app.use(cors({ origin: origins }));
app.use(express.json({ limit: "10kb" })); // records are small; reject huge bodies

// ---------- GET / : API guide for the marker ----------
const escapeHtml = (text) =>
  String(text).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c]);

const SAMPLE_BODY = {
  title: "Broken classroom light",
  category: "Electrical",
  description: "The light in Room B12 does not switch on.",
  status: "Pending",
};

