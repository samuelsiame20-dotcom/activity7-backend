  const base = escapeHtml(baseUrl);
  const fieldRows = Object.entries(FIELD_RULES)
    .map(([name, r]) => `<tr><td><code>${name}</code></td><td>Text, ${r.min} to ${r.max} characters (trimmed)</td></tr>`)
    .join("");
