app.get("/", (req, res) => {
  const baseUrl = process.env.PUBLIC_BASE_URL || `${req.protocol}://${req.get("host")}`;
  res.status(200).type("html").send(guidePage(baseUrl.replace(/\/+$/, "")));
});

// ---------- GET /health ----------
app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "connected" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ message: "Database is not reachable.", status: "error", database: "disconnected" });
  }
});

// ---------- Record routes ----------
app.use("/api/records", require("./routes/records"));

// ---------- Unknown route -> 404 JSON ----------
app.use((req, res) => {
  res.status(404).json({ message: `Route ${req.method} ${req.path} does not exist.` });
});

// ---------- Error handler (4 parameters) ----------
// eslint-disable-next-line no-unused-vars
app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed") {
    return res.status(400).json({ message: "Malformed JSON in request body." });
  }
  if (error.type === "entity.too.large") {
    return res.status(413).json({ message: "Request body is too large." });
  }
  // Log the details for you; send only a safe message to the client.
  console.error(`${req.method} ${req.originalUrl} failed:`, error);
  res.status(500).json({ message: "Unexpected server error. Please try again later." });
});

// ---------- Start ----------
const port = process.env.PORT || 3000;

initDatabase(pool)
  .catch((error) => {
    // Keep the server up so /health can report 503 instead of the service crashing.
    console.error("Database setup failed:", error.message);
  })
  .finally(() => {
    app.listen(port, "0.0.0.0", () => {
      console.log(`Server listening on port ${port}`);
    });
  });
